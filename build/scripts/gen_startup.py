#!/usr/bin/env python3
"""Generates gcc_support/startup_hc32f460.S from the ARM startup (startup_hc32f46x.s)
so that the vector table order is identical. Keil logic replicated:
Reset: SRAM3 wait states -> SystemInit -> (__main: copy .data, zero .bss) -> main."""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
src = (ROOT.parent / "firmware" / "source" / "main" / "hdsc32core" / "startup_hc32f46x.s").read_text(errors="replace")
tbl = src.split("__Vectors       DCD")[1].split("__Vectors_End")[0]
tbl = "DCD" + tbl
ents = []
for line in tbl.splitlines():
    m = re.match(r"\s*DCD\s+(\S+)", line)
    if m: ents.append(m.group(1))
print(len(ents), "vector entries")
weak = [e for e in ents if e not in ("__initial_sp", "Reset_Handler", "0")]
weak = list(dict.fromkeys(weak))
o = []
o.append("""/* Generated by scripts/gen_startup.py from HDSC startup_hc32f46x.s (ARM). Do not edit. */
    .syntax unified
    .cpu cortex-m4
    .fpu fpv4-sp-d16
    .thumb

    .section .isr_vector,"a",%progbits
    .type __Vectors, %object
__Vectors:
""")
for e in ents:
    o.append("    .word %s\n" % ("_estack" if e == "__initial_sp" else e))
o.append("""__Vectors_End:
    .size __Vectors, .-__Vectors

    .section .text.Reset_Handler,"ax",%progbits
    .weak Reset_Handler
    .type Reset_Handler, %function
    .thumb_func
Reset_Handler:
    /* Set the stack pointer explicitly (the Keil startup does this; do not rely on the bootloader) */
    LDR R0, =_estack
    MOV SP, R0
    /* SET_SRAM3_WAIT (identical to ARM startup) */
    LDR R0, =0x40050804
    MOV R1, #0x77
    STR R1, [R0]
    LDR R0, =0x4005080C
    MOV R1, #0x77
    STR R1, [R0]
    LDR R0, =0x40050800
    MOV R1, #0x1100
    STR R1, [R0]
    LDR R0, =0x40050804
    MOV R1, #0x76
    STR R1, [R0]
    LDR R0, =0x4005080C
    MOV R1, #0x76
    STR R1, [R0]
    /* Same order as Keil: SystemInit first, then runtime init (copy .data / zero .bss) */
    LDR R0, =SystemInit
    BLX R0
    /* copy .data from flash */
    LDR R0, =_sdata
    LDR R1, =_edata
    LDR R2, =_sidata
1:  CMP R0, R1
    BCS 2f
    LDR R3, [R2], #4
    STR R3, [R0], #4
    B 1b
2:  /* zero .bss */
    LDR R0, =_sbss
    LDR R1, =_ebss
    MOVS R2, #0
3:  CMP R0, R1
    BCS 4f
    STR R2, [R0], #4
    B 3b
4:  LDR R0, =__libc_init_array
    BLX R0
    LDR R0, =main
    BX R0
    .ltorg
    .size Reset_Handler, .-Reset_Handler

    .section .text.Default_Handler,"ax",%progbits
    .thumb_func
Default_Handler:
    B .
    .size Default_Handler, .-Default_Handler

""")
for w in weak:
    o.append("    .weak %s\n    .thumb_set %s, Default_Handler\n" % (w, w))
(ROOT / "gcc_support" / "startup_hc32f460.S").write_text("".join(o))
